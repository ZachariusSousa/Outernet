import json
from pathlib import Path
from PIL import Image,ImageDraw
from pixel_clean import palette
root=Path(__file__).resolve().parents[1]/'art/textures';colors=palette()
patterns={'wood':(9,10),'parquet':(9,10),'fabric':(7,8),'metal':(2,3),'rug':(16,18),'snow':(6,5),'stone':(4,5),'concrete':(3,4),'leaf':(19,20),'tv-screen':(1,16),'white':(7,7),'velvet':(22,23)}
manifest=[]
for name,(a,b) in patterns.items():
 size=(128,64) if name=='tv-screen' else (64,64);im=Image.new('RGB',size,colors[a]);d=ImageDraw.Draw(im)
 if name in ['wood','parquet']:
  for y in range(0,64,16):d.rectangle((0,y,63,y),fill=colors[b]);d.line((y*3%64,y,y*3%64,y+15),fill=colors[b])
 elif name=='tv-screen':
  for x in range(0,128,8):d.rectangle((x,30-(x%24),x+5,63),fill=colors[16 if x%16 else 4])
 elif name=='rug':
  d.rectangle((3,3,60,60),outline=colors[8],width=3)
  for x in range(12,60,16):d.rectangle((x,16,x+7,47),fill=colors[b])
 elif name not in ['white','metal']:
  for x,y in [(8,12),(36,28),(20,48),(52,8)]:d.rectangle((x,y,x+7,y+1),fill=colors[b])
 im.save(root/(name+'.png'));manifest.append(dict(file=name+'.png',size=list(size),source='procedural',license='CC0-1.0',author='OuterNet',density=32))
(root/'textures.json').write_text(json.dumps(manifest,indent=2))
(root/'CREDITS.md').write_text('# Texture credits\n\nAll current PNG textures listed in textures.json are original procedural stand-ins generated by world/tools/standin_textures.py; CC0 1.0. No external packs have been incorporated. Replace with CC0 packs or cleaned special artwork as it becomes available.\n')
